def test_replace_once_rejects_empty_old():
    with pytest.raises(NetworkError, match="must not be empty"):
        replace_once("some non-empty text", "", "replacement", "test.c")


def test_check_source_blocks_line_continuation_and_windows_paths():
    # Spliced line continuations
    with pytest.raises(SourceRejected):
        check_source("void f(void){ _\\\n_asm__(\"nop\"); }")
    with pytest.raises(SourceRejected):
        check_source("#inc\\\nlude <stdio.h>")

    # Windows path traversal
    with pytest.raises(SourceRejected):
        check_source('#include "..\\..\\secret.h"')
    with pytest.raises(SourceRejected):
        check_source('#include "C:\\Windows\\system.ini"')

    # Include with comments
    with pytest.raises(SourceRejected):
        check_source('#/*comment*/include "../../secret.h"')


def test_hostenv_windows_path_mnt_root():
    # /mnt/c should map to C:\ without falling back to WSL UNC path
    assert windows_path("/mnt/c") == "C:\\"
    assert windows_path("/mnt/c/Users/test") == "C:\\Users\\test"


def test_tracefile_csv_with_leading_comment_and_bools():
    csv_text = "# Generated by profiler\n# Run on 2026-10-30\naddress,hits\n0x401000,10\n0x402000,5\n"
    tf = parse_trace(csv_text, "test.csv")
    assert len(tf.hits) == 2
    assert tf.hits[0].address == 0x401000
    assert tf.hits[0].count == 10
    assert tf.hits[1].address == 0x402000
    assert tf.hits[1].count == 5

    # JSON with booleans should not interpret True/False as address 1/0
    json_text = '[{"address": true, "hits": 5}, {"address": "0x401000", "hits": 2}]'
    tf_json = parse_trace(json_text, "test.json")
    assert len(tf_json.hits) == 1
    assert tf_json.hits[0].address == 0x401000


def test_scoring_diff_reorder_count_decrement():
    # Target has 1 'nop', candidate has 3 'nop's and extra instruction
    # 'nop' moved count is 1. Only 1 row should be marked 'o', not all of them.
    t = FunctionObj("f", "x86", False, b"\x90", [])
    c = FunctionObj("f", "x86", False, b"\x90\x90\x90", [])
    res = diff(t, c)
    assert isinstance(res, DiffResult)
    marks = [m for m, _, _ in res.rows if m != " "]
    assert marks.count("o") <= 1


def test_pe_decode_intra_function_jump_to_vram():
    # 32-bit x86: loop jump back to offset 0 (vram = 0x401000)
    # 0x401000: inc eax (40)
    # 0x401001: jmp rel32 to 0x401000 (E9 FA FF FF FF -> target 0x401000)
    code = b"\x40\xE9\xFA\xFF\xFF\xFF"
    vram = 0x401000
    md = pe._md("x86")
    md.detail = True
    _lines, _count, refs = pe._decode(code, vram, "x86", 0x400000, 0x405000, absolute=True, md=md)
    # The jump to 0x401000 is an intra-function loop back to start of function; should not be in refs
    assert len(refs) == 0


def test_pe_decode_short_jump_not_reloc():
    # 0x401000: jmp rel8 to 0x401000 (EB FE)
    code = b"\xEB\xFE"
    vram = 0x401000
    md = pe._md("x86")
    md.detail = True
    _lines, _count, refs = pe._decode(code, vram, "x86", 0x400000, 0x405000, absolute=True, md=md)
    assert len(refs) == 0
